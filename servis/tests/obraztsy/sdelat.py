"""Изготовление образцов платёжек для сквозных проверок.

    python servis/tests/obraztsy/sdelat.py

Три файла формы 0401060 с одними и теми же реквизитами, но свёрстанные
по-разному:

- `platezhka-0401060.pdf` — цифры идут подряд, как в обычной печати;
- `platezhka-vrazryadku.pdf` — цифры разнесены по клеткам бланка, и движок
  чтения видит `6 1 6 1 2 5 8 5 5 3 2 6` вместо ИНН;
- `platezhka-podpisi-otdelno.pdf` — то же плюс подписи клеток («ИНН», «Сч. №»,
  «Плательщик») сдвинуты по высоте и попадают в отдельные строки, оторванные
  от значений. Именно так была свёрстана платёжка, на которой разбор
  споткнулся у настоящего пользователя: искать значение рядом с подписью
  в такой форме бесполезно, реквизиты опознаются по контрольным суммам.

**pymupdf нужен только здесь.** Он под AGPL, в поставку продукта не идёт
и в зависимостях сервиса не числится: этот скрипт запускают один раз,
а тесты читают уже готовые PDF нашим обычным движком, pdfplumber.

Реквизиты — из открытой платёжки индивидуального предпринимателя; суммы,
назначение платежа и получатель к делу отношения не имеют.
"""
from __future__ import annotations

from pathlib import Path

PAPKA = Path(__file__).resolve().parent
SHRIFT = r"C:\Windows\Fonts\arial.ttf"

# Шаг между цифрами. При 9.5 промежуток меньше порога и движок склеивает
# цифры сам; при 14.0 — шире, и число рвётся на отдельные ячейки.
# имя файла -> (шаг между цифрами, сдвиг подписей клеток по высоте)
VARIANTY = {
    "platezhka-0401060.pdf": (9.5, 0.0),
    "platezhka-vrazryadku.pdf": (14.0, 0.0),
    "platezhka-podpisi-otdelno.pdf": (14.0, 9.0),
}


def sdelat(imya: str, shag: float, sdvig: float) -> int:
    import pymupdf

    doc = pymupdf.open()
    page = doc.new_page(width=595, height=842)
    page.insert_font(fontname="ar", fontfile=SHRIFT)

    def p(x: float, y: float, text: str, kegl: float = 8) -> None:
        page.insert_text((x, y), text, fontname="ar", fontsize=kegl)

    def podpis(x: float, y: float, text: str, kegl: float = 8) -> None:
        """Подпись клетки. В части бланков она стоит не вровень со значением,
        и тогда при чтении уезжает в отдельную строку."""
        page.insert_text((x, y + sdvig), text, fontname="ar", fontsize=kegl)

    def cifry(x: float, y: float, znaki: str, kegl: float = 8) -> None:
        """Цифры по клеткам бланка — каждая на своём месте."""
        for nomer, znak in enumerate(znaki):
            page.insert_text((x + nomer * shag, y), znak, fontname="ar", fontsize=kegl)

    p(480, 40, "0401060")
    p(60, 60, "27.08.2026")
    p(180, 60, "27.08.2026")
    p(60, 70, "Поступ. в банк плат.", 6)
    p(180, 70, "Списано со сч. плат.", 6)
    p(60, 95, "ПЛАТЕЖНОЕ ПОРУЧЕНИЕ № 88", 9)
    p(260, 95, "27.08.2026")
    p(340, 95, "Электронно")
    p(60, 125, "Сумма")
    p(60, 134, "прописью", 6)
    p(120, 125, "Двадцать две тысячи триста двадцать три рубля 00 копеек")

    podpis(60, 165, "ИНН")
    cifry(85, 165, "616125855326")
    podpis(250, 165, "КПП")
    p(275, 165, "0")  # у ИП КПП нет, в бланке печатается нолём
    p(350, 165, "Сумма")
    p(400, 165, "22323-00")

    p(60, 180, "Индивидуальный предприниматель Шульмина Надежда")
    p(60, 190, "Алексеевна")  # наименование не влезает в строку и переносится
    podpis(330, 205, "Сч. №")
    cifry(365, 205, "40802810003500013642")
    p(60, 225, "Плательщик", 6)

    p(60, 240, 'ООО "Банк Точка" г. Москва')
    podpis(350, 240, "БИК")
    cifry(380, 240, "044525104")
    podpis(330, 252, "Сч. №")
    cifry(365, 252, "30101810745374525104")
    p(60, 265, "Банк плательщика", 6)

    p(60, 280, 'Филиал "Центральный" Банка ВТБ (ПАО) г. Москва')
    podpis(350, 280, "БИК")
    cifry(380, 280, "044525411")
    podpis(330, 292, "Сч. №")
    cifry(365, 292, "30101810145250000411")
    p(60, 305, "Банк получателя", 6)

    p(60, 320, "ИНН")
    p(85, 320, "7716509296")
    p(250, 320, "КПП")
    p(275, 320, "772701001")
    p(330, 320, "Сч. №")
    cifry(365, 320, "40702810801010000677")
    p(60, 335, "ЭР СОФТ, ООО")
    p(60, 375, "Получатель", 6)

    p(60, 400, "Оплата по счёту Лицензионное ПО - WEB 4 шт, период 1 мес Без НДС")
    p(60, 425, "Назначение платежа", 6)

    doc.subset_fonts()  # иначе шрифт целиком, и файл под мегабайт
    doc.save(PAPKA / imya, garbage=4, deflate=True)
    doc.close()
    return (PAPKA / imya).stat().st_size


if __name__ == "__main__":
    for imya, (shag, sdvig) in VARIANTY.items():
        print(f"{imya:34} {sdelat(imya, shag, sdvig):>7} байт")
